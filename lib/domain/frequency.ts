/**
 * Тунгийн давтамжийн код.
 *
 * Мужтай код (q4_6h г.м.) нь эмнэлзүйн бодит бичиглэл — "4–6 цаг тутам".
 * Тооцоололд DOSES_PER_DAY дахь консерватив (бага) утгыг ашиглана.
 */
export type FrequencyCode =
  | "od"
  | "bd"
  | "tds"
  | "qds"
  | "q4h"
  | "q6h"
  | "q8h"
  | "q12h"
  | "q4_6h"
  | "q6_8h"
  | "q8_12h";

/** Код бүрийн өдрийн тунгийн тоо. Тооцоолол зөвхөн энэ хүснэгтээс уншина. */
export const DOSES_PER_DAY: Record<FrequencyCode, number> = {
  od: 1,
  bd: 2,
  tds: 3,
  qds: 4,
  q4h: 6,
  q6h: 4,
  q8h: 3,
  q12h: 2,
  q4_6h: 4,
  q6_8h: 3,
  q8_12h: 2,
};
