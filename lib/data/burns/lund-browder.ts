import type { AgeBand, BodyRegionId } from "../../domain/body-region";

/**
 * Lund-Browder — биеийн гадаргуугийн хувь, бүс × насны ангилалаар.
 *
 * ═══ ЯАГААД ЭНЭ ХҮСНЭГТ ЗААВАЛ ХЭРЭГТЭЙ ВЭ ═══
 *
 * Естийн дүрэм (Rule of Nines) нь ЗӨВХӨН хоёр ангилалтай: «хүүхэд» ба
 * «насанд хүрэгч». Тэр «хүүхэд» багана нь НЯРАЙН харьцаа (толгой 19%).
 * 14 настай өсвөр насныхныг тэр баганаар тооцвол толгойг нь 19% гэж
 * үзэх бөгөөд бодит утга нь 11% юм — 73% хэтрүүлэлт.
 *
 * 45 кг жинтэй 14 настай хүүхдийн толгой бүтэн түлэгдсэн тохиолдолд:
 *   Естийн дүрмээр  4 × 45 × 19 = 3 420 мл / 24 цаг
 *   Lund-Browder-ээр 4 × 45 × 11 = 1 980 мл / 24 цаг
 * Зөрүү нь 1.4 литр илүүдэл шингэн — уушгины хаван, тайвшралын хамшинжийн
 * бодит эрсдэл.
 *
 * ═══ ЭХ СУРВАЛЖ ═══
 *
 * Хүснэгтийн НАСААР ӨӨРЧЛӨГДӨХ гурван мөрийг (A/B/C) хоёр бие даасан
 * эх сурвалжаар тулгаж баталгаажуулав:
 *
 *   1. Miminas DA. A critical evaluation of the Lund and Browder chart.
 *      Wounds UK. Хүснэгтэд шууд хэвлэсэн утга:
 *        A (толгойн тал):      9½  8½  6½  5½  4½  3½
 *        B (нэг гуяны тал):    2¾  3¼  4   4¼  4½  4¾
 *        C (нэг шилбэний тал): 2½  2½  2¾  3   3¼  3½
 *
 *   2. Lund and Browder chart — нэгтгэсэн лавлах (тогтмол бүсүүд ба
 *      A/B/C утгууд бүрэн). Дээрхтэй бүрэн таарсан.
 *
 *   Гурав дахь баталгаа — АРИФМЕТИК: багана бүрийн нийлбэр ЯГ 100%
 *   байх ёстой. Тогтмол бүсүүд нийт 60%, хувьсах хэсэг (2A + 4B + 4C)
 *   нь зургаан ангилал бүрд яг 40% болно. Энэ шалгуур нь эх сурвалж
 *   дэх хэвлэлийн алдааг илрүүлдэг: нэг лавлах B-ийн 10 насны утгыг
 *   4½ гэж хэвлэсэн байсан бөгөөд тэр тохиолдолд нийлбэр 101% болно.
 *   Тиймээс 4¼ зөв. `totalPercent()` тест бүрд үүнийг шалгана.
 *
 * ═══ ЭНД БАЙГАА УТГА НЬ БҮТЭН БҮС ═══
 *
 * Сонгодог хүснэгт нь толгой, гуя, шилбийг ХАГАСААР нь (A/B/C) өгдөг —
 * учир нь цаасан диаграм дээр урд/ар талыг тусад нь будна. Энэ апп нь
 * бүсийг бүтнээр нь сонгодог тул:
 *   толгой = 2A · нэг гуя = 2B · нэг шилбэ = 2C
 *
 * ⚠️ Хагасыг нь тэмдэглэх шаардлагатай бол `BurnSelection.fraction = 0.5`
 *    ашиглана — хүснэгтийн утгыг ХАГАСЛАЖ БИЧИХГҮЙ.
 */
export type RegionPercentages = Readonly<Record<AgeBand, number>>;

/** Хүснэгтийн нэг мөр — эх сурвалж дээрх баганын дарааллаар. */
type Row = readonly [
  infant: number,
  y1: number,
  y5: number,
  y10: number,
  y15: number,
  adult: number,
];

/** Мөрийг нэрлэсэн ангилал руу буулгана. Дараалал нь эх сурвалжийнхтэй нэг. */
const band = (row: Row): RegionPercentages => ({
  infant: row[0],
  y1: row[1],
  y5: row[2],
  y10: row[3],
  y15: row[4],
  adult: row[5],
});

/** Бүх насанд тогтмол утгатай бүс. */
const fixed = (percent: number): RegionPercentages =>
  band([percent, percent, percent, percent, percent, percent]);

/**
 * ⚠️ `Partial` БИШ — бүтэн `Record`. Шинэ `BodyRegionId` нэмээд энд
 * бичихээ мартвал build УНАНА. Энэ нь зориудын хамгаалалт: дутуу бүс
 * нь чимээгүйхэн 0% болж, БНГТ%-ийг дутуу тооцоолно.
 */
export const LUND_BROWDER: Readonly<Record<BodyRegionId, RegionPercentages>> = {
  // Насаар өөрчлөгддөг — толгой жижгэрч, доод мөч уртсана.
  head: band([19, 17, 13, 11, 9, 7]), //            2A
  thigh_left: band([5.5, 6.5, 8, 8.5, 9, 9.5]), //  2B
  thigh_right: band([5.5, 6.5, 8, 8.5, 9, 9.5]), // 2B
  leg_left: band([5, 5, 5.5, 6, 6.5, 7]), //        2C
  leg_right: band([5, 5, 5.5, 6, 6.5, 7]), //       2C

  // Бүх насанд тогтмол.
  neck: fixed(2),
  trunk_anterior: fixed(13),
  trunk_posterior: fixed(13),
  buttock_left: fixed(2.5),
  buttock_right: fixed(2.5),
  genitalia: fixed(1),
  upper_arm_left: fixed(4),
  upper_arm_right: fixed(4),
  forearm_left: fixed(3),
  forearm_right: fixed(3),
  hand_left: fixed(2.5),
  hand_right: fixed(2.5),
  foot_left: fixed(3.5),
  foot_right: fixed(3.5),
};

/** Гарын алга (хуруу орсон) ≈ БНГТ-ийн 1%. Тархмал гэмтэлд ашиглана. */
export const PALM_PERCENT = 1;

/**
 * Насны ангилалын нийлбэр. ЯГ 100 байх ёстой — тест бүрд шалгана.
 *
 * Хөвөгч цэгийн нийлбэрт 0.1-ийн алдаа орж болзошгүй тул дугуйрсан
 * утгыг буцаана (2.5 + 2.5 + 3.5 … нь binary float-д яг таарахгүй).
 */
export const totalPercent = (ageBand: AgeBand): number =>
  Math.round(
    Object.values(LUND_BROWDER).reduce(
      (sum, region) => sum + region[ageBand],
      0,
    ) * 10,
  ) / 10;
